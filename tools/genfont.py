#!/usr/bin/env python3
"""Rasterise the UI fonts into antialiased glyph tables for the kernel.

    python3 tools/genfont.py > gfx/fontdata.c

The kernel has no font engine, so every face/size it uses is pre-rendered
here (with FreeType hinting, via Pillow) into 8-bit coverage bitmaps.
"""

import sys

from PIL import Image, ImageDraw, ImageFont

TT = '/usr/share/fonts/truetype/'
INTER = '/usr/share/fonts/opentype/inter/'
ASCII = ''.join(chr(c) for c in range(32, 127))
DIGITS = ' 0123456789:'

# Inter stands in for the San Francisco look. Small sizes get a gamma below 1 so
# the unhinted strokes come out as dark as a hinted system font would.
# name, file, pixel size, characters, gamma
FONTS = [
    ('font_ui', INTER + 'Inter-Regular.otf', 12, ASCII, 0.8),
    ('font_ui_bold', INTER + 'Inter-SemiBold.otf', 12, ASCII, 0.85),
    ('font_title', INTER + 'Inter-SemiBold.otf', 13, ASCII, 0.85),
    ('font_menu', INTER + 'Inter-Regular.otf', 13, ASCII, 0.8),
    ('font_menu_bold', INTER + 'Inter-Bold.otf', 13, ASCII, 0.9),
    ('font_mono', TT + 'dejavu/DejaVuSansMono.ttf', 13, ASCII, 1.0),
    ('font_heading', INTER + 'Inter-SemiBold.otf', 15, ASCII, 0.9),
    ('font_big', INTER + 'Inter-Regular.otf', 20, ASCII, 1.0),
    ('font_big_bold', INTER + 'Inter-Bold.otf', 22, ASCII, 1.0),
    ('font_date', INTER + 'Inter-SemiBold.otf', 21, ASCII, 1.0),
    ('font_display', INTER + 'InterDisplay-Medium.otf', 30, ASCII, 1.0),
    ('font_clock', INTER + 'InterDisplay-SemiBold.otf', 104, DIGITS, 1.0),
]


def render(name, path, size, chars, gamma):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    for code in range(32, 127):
        ch = chr(code)
        if ch not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bitmap)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255)
            if gamma != 1.0:
                im = im.point(lambda v: round(255 * (v / 255) ** gamma))
            bitmap += im.tobytes()
        glyphs.append((w, h, x0, y0, adv, off))
    return ascent, descent, glyphs, bitmap


def main():
    out = sys.stdout
    out.write('/* Generated by tools/genfont.py. Do not edit. */\n\n#include "font.h"\n\n')
    for name, path, size, chars, gamma in FONTS:
        ascent, descent, glyphs, bitmap = render(name, path, size, chars, gamma)
        out.write(f'/* {path.rsplit("/", 1)[-1]} {size}px */\n')
        out.write(f'static const uint8_t {name}_bits[{max(1, len(bitmap))}] = {{\n')
        for i in range(0, len(bitmap), 40):
            out.write('    ' + ','.join(str(b) for b in bitmap[i:i + 40]) + ',\n')
        if not bitmap:
            out.write('    0,\n')
        out.write('};\n')
        out.write(f'static const glyph_t {name}_glyphs[95] = {{\n')
        for g in glyphs:
            out.write('    {%d, %d, %d, %d, %d, %d},\n' % g)
        out.write('};\n')
        out.write(f'const font_t {name} = {{ {ascent + descent}, {ascent}, {name}_glyphs, {name}_bits }};\n\n')


if __name__ == '__main__':
    main()
