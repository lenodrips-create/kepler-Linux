#!/bin/sh
# Regenerates net/ca_roots.c, the root certificates HTTPS trusts, from the
# Mozilla bundle (Debian/Ubuntu ca-certificates) using BearSSL's brssl tool:
#
#     make -C <bearssl source>          # builds build/brssl
#     tools/gen_ca_roots.sh <bearssl source>/build/brssl > net/ca_roots.c
set -e
BRSSL=${1:-brssl}
CERTS=${CERTS:-/usr/share/ca-certificates/mozilla}
echo "/* Generated by tools/gen_ca_roots.sh from the Mozilla root store ($(ls "$CERTS" | wc -l) roots). Do not edit. */"
echo
echo '#include "bearssl.h"'
"$BRSSL" ta "$CERTS"/*.crt 2>/dev/null |
    sed -e 's/^static const br_x509_trust_anchor TAs\[\([0-9]*\)\]/const br_x509_trust_anchor ca_roots[\1]/' \
        -e 's/^#define TAs_NUM *\([0-9]*\)/const size_t ca_roots_count = \1;/'
